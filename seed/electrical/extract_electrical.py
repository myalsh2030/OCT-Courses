WIDE_SPACE = 0.45               # ما جاوزها وشارك حرفاً موضعَه فهو تطويل ضبط
KASHIDA = "ُـ"        # الدمّة صفرية العرض هنا هي محرف التطويل
MARKS = re.compile(r"[ً-ْٰ]")
ARABIC = re.compile(r"[؀-ۿ]")
